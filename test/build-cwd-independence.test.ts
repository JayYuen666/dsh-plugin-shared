// 构建产物的 cwd 无关性：模块横幅的路径基准是 rolldown 的 `cwd` 选项，不是 process.cwd()。
// 这条回归直接拿真实 rolldown 跑两次不同 process.cwd，判据是逐字节相等——不靠文本后处理。
import { describe, it } from "vitest";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { rolldown } from "rolldown";
import { buildHostEntries } from "../lib/build-host.ts";

/** 一个最小包根：依赖段非空（构建编排会拒绝空外置集），入口引一个自有 lib 模块。 */
async function fixture(): Promise<string> {
  const temporary = await mkdtemp(path.join(tmpdir(), "dsh-cwd-"));
  const root = await realpath(temporary);
  await mkdir(path.join(root, "lib"), { recursive: true });
  await writeFile(
    path.join(root, "package.json"),
    `${JSON.stringify({ name: "cwd-fixture", dependencies: { "@scope/external": "1.0.0" } }, null, 2)}\n`,
    "utf8",
  );
  await writeFile(
    path.join(root, "host.ts"),
    'import { bump } from "./lib/a.ts";\nexport const value = bump(1);\n',
    "utf8",
  );
  await writeFile(
    path.join(root, "lib", "a.ts"),
    "export function bump(n: number): number {\n  return n + 1;\n}\n",
    "utf8",
  );
  return root;
}

/**
 * 从指定 process.cwd 构建同一份包。
 * @param root - 包根绝对路径
 * @param cwd - 构建时的 process.cwd
 * @returns 产物正文
 */
async function buildFrom(root: string, cwd: string): Promise<string> {
  const before = process.cwd();
  process.chdir(cwd);
  try {
    const artifacts = await buildHostEntries({
      root,
      rolldown,
      entries: [
        {
          source: "host.ts",
          output: "host.js",
          header: "// GENERATED by build-host.mjs\n",
        },
      ],
    });
    const artifact = artifacts.find((item) => item.output === "host.js");
    if (artifact === undefined) {
      assert.fail("产物清单里没有 host.js");
    }
    return artifact.code;
  } finally {
    process.chdir(before);
  }
}

describe("构建产物与 process.cwd 无关", () => {
  it("从包根与包根外各构建一次 ⇒ 逐字节相等，且横幅是包根相对路径", async () => {
    const root = await fixture();
    try {
      const fromOutside = await buildFrom(root, path.dirname(root));
      const fromPackage = await buildFrom(root, root);
      assert.equal(fromOutside, fromPackage);
      assert.ok(fromOutside.includes("// lib/a.ts"), fromOutside.slice(0, 400));
      assert.ok(fromOutside.includes("// host.ts"), fromOutside.slice(0, 400));
      assert.ok(!fromOutside.includes(root), "产物里不得出现构建机的绝对包根");
      assert.ok(!fromOutside.includes("#region"), "生产构建不应有 HMR region 横幅");
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });
});
