// lib/canonicalize-region-paths 单元测试：模块横幅必须按 rolldown 的真实基准解析，
// 不能靠“先删 ../ 再猜前缀”。内部构建已不再调用本函数（基准由 rolldown 的 cwd 固定），
// 这里固定的是公开子路径的单次处理契约。
import { describe, it } from "vitest";
import assert from "node:assert/strict";
import { canonicalizeRegionPaths } from "../lib/canonicalize-region-paths.ts";

/** 包根：/repo/plugins/foo，父目录 /repo/plugins。 */
const PKG_DIR = "/repo/plugins/foo";
const PARENT_DIR = "/repo/plugins";
const WORKSPACE = "/repo";

/** 产物里的一行真代码：证明非横幅字节一个不动。 */
const CODE_LINE = "const a = 1;";

/** 最常见的自有模块横幅与原始路径，重复断言里共用。 */
const LIB_A_MARK = "// lib/a.ts";
const SHARED_X_MARK = "// shared/lib/x.ts";
const FOO_LIB = "foo/lib/a.ts";

/** 产物首行的生成说明（builder 写的，不参与规范化）。 */
const GENERATED_BANNER = "// GENERATED by build-host.mjs";

/**
 * 拼一段产物文本（说明行 + 逐条模块横幅 + 一行真代码）。
 * @param marks - 各模块路径，按 rolldown 的写法逐条成行
 * @param prefix - 横幅前缀；生产是 `// `，HMR 是 `//#region `
 * @returns 可直接喂给被测函数的多行文本
 */
function artifactOf(marks: readonly string[], prefix = "// "): string {
  const rows = marks.map((mark) => `${prefix}${mark}`);
  return [GENERATED_BANNER, ...rows, CODE_LINE].join("\n");
}

/**
 * 抽出产物文本里的全部横幅行。
 * @param code - 产物文本
 * @returns 命中的行
 */
function markerLines(code: string): string[] {
  return code.split("\n").filter((line) => line.startsWith("// ") && line !== GENERATED_BANNER);
}

/**
 * 改一段产物、只回生产横幅行。
 * @param marks - 原始模块路径
 * @param pkgDir - 包根
 * @param baseDir - 标记路径的基准
 * @returns 折完之后的横幅行
 */
function folded(
  marks: readonly string[],
  pkgDir: string = PKG_DIR,
  baseDir: string = PKG_DIR,
): string[] {
  return markerLines(canonicalizeRegionPaths(artifactOf(marks), pkgDir, baseDir));
}

describe("生产横幅：按真实基准解析，不猜前缀", () => {
  it("base = 包根：自有模块原样，说明行与代码行不动", () => {
    const code = artifactOf(["lib/a.ts", "host.ts"]);
    assert.equal(canonicalizeRegionPaths(code, PKG_DIR, PKG_DIR), code);
  });

  it("base = 父目录：自有模块收包名段，依赖与 node_modules 保留父目录相对形态", () => {
    const marks = [FOO_LIB, "shared/lib/x.ts", "node_modules/x/index.js"];
    assert.deepEqual(folded(marks, PKG_DIR, PARENT_DIR), [
      LIB_A_MARK,
      SHARED_X_MARK,
      "// node_modules/x/index.js",
    ]);
  });

  it("base = 工作区根：自有模块收两段，同级依赖只收父目录段并保留包名", () => {
    assert.deepEqual(
      folded(["plugins/foo/lib/a.ts", "plugins/shared/lib/x.ts"], PKG_DIR, WORKSPACE),
      [LIB_A_MARK, SHARED_X_MARK],
    );
  });

  it("base = 兄弟目录：行首 ../ 由基准解析消掉，不靠字符串裁剪", () => {
    assert.deepEqual(
      folded(["../plugins/foo/lib/a.ts", "../plugins/shared/lib/x.ts"], PKG_DIR, "/repo/other"),
      [LIB_A_MARK, SHARED_X_MARK],
    );
  });

  it("hmr 的 //#region 与生产 // 共用同一套解析；//#endregion 不改", () => {
    const code = ["//#region plugins/foo/lib/a.ts", "//#endregion", "// plugins/foo/lib/a.ts"].join(
      "\n",
    );
    assert.equal(
      canonicalizeRegionPaths(code, PKG_DIR, WORKSPACE),
      ["//#region lib/a.ts", "//#endregion", LIB_A_MARK].join("\n"),
    );
  });
});

describe("路径归属：完整路径段判定，包外路径必须原样保留", () => {
  it("相对层级更深、实际目标在包外 ⇒ 不剥任何段", () => {
    const raw = "../../plugins/foo/lib/x.ts";
    assert.deepEqual(folded([raw], PKG_DIR, "/repo/work"), [`// ${raw}`]);
  });

  it("base 在兄弟目录时，cwd 内同名子目录不等于包根", () => {
    const raw = "foo/src/a.ts";
    // 解析结果是 <bar>/foo/src/a.ts：不属于本包，但属于包根父目录下的兄弟包 bar。
    // 按“兄弟包相对父目录”的形态保留，不能折成本包的 src/a.ts。
    assert.deepEqual(folded([raw], "/repo/foo", "/repo/bar"), ["// bar/foo/src/a.ts"]);
    assert.deepEqual(folded(["../foo/src/a.ts"], "/repo/foo", "/repo/bar"), ["// src/a.ts"]);
  });

  it("包内目录与父目录同名：第一次处理只收真实前缀", () => {
    assert.deepEqual(folded(["plugins/foo/plugins/x.ts"], PKG_DIR, WORKSPACE), ["// plugins/x.ts"]);
  });

  it("包内目录与包名同名：按 base=/repo 解析到包内真实子目录", () => {
    assert.deepEqual(folded(["foo/foo/a.ts"], "/repo/foo", "/repo"), ["// foo/a.ts"]);
  });

  it("base 在包根内部：缺失的目录段被补回", () => {
    assert.deepEqual(folded(["a.ts", "../lib/b.ts"], PKG_DIR, `${PKG_DIR}/src`), [
      "// src/a.ts",
      "// lib/b.ts",
    ]);
  });

  it("绝对路径按段归属：包内折回、包外原样", () => {
    assert.deepEqual(folded([`${PKG_DIR}/lib/a.ts`, "/other/lib/b.ts"], PKG_DIR, WORKSPACE), [
      LIB_A_MARK,
      "// /other/lib/b.ts",
    ]);
  });

  it("目标正好是包根或父目录：没有可删的段，保留原始路径", () => {
    assert.deepEqual(folded(["foo"], "/repo/foo", "/repo"), ["// foo"]);
    assert.deepEqual(folded(["plugins"], PKG_DIR, WORKSPACE), ["// plugins"]);
    assert.deepEqual(folded([".."], "/repo/foo", "/repo"), ["// .."]);
  });

  it("目标比包根短：不是包根的子路径，原样保留", () => {
    assert.deepEqual(folded(["../.."], "/repo/foo", "/repo"), ["// ../.."]);
  });

  it("点段被归一：./ 前缀不影响归属判断", () => {
    assert.deepEqual(folded(["./foo/lib/a.ts"], PKG_DIR, PARENT_DIR), [LIB_A_MARK]);
    assert.deepEqual(folded(["/.."], PKG_DIR, WORKSPACE), ["// /.."]);
  });
});

describe("契约是单次处理，不承诺幂等", () => {
  it("同一字符串二次处理不属于契约：canonical 文本不携带参照系", () => {
    const once = canonicalizeRegionPaths(artifactOf(["foo/foo/a.ts"]), "/repo/foo", "/repo");
    const twice = canonicalizeRegionPaths(once, "/repo/foo", "/repo");
    // 第一次是包内 foo/a.ts；第二次把它当成 base 下的 foo/a.ts，只剩 a.ts。
    // 这不是可修的前缀顺序问题：两条路径在纯字符串上同形，调用方只应处理原始产物一次。
    assert.deepEqual(markerLines(twice), ["// a.ts"]);
  });
});

describe("路径形状的边界", () => {
  it("pkgDir 末段带分隔符 ⇒ 与不带时同一结果", () => {
    const code = artifactOf([FOO_LIB]);
    assert.equal(
      canonicalizeRegionPaths(code, `${PKG_DIR}/`, PARENT_DIR),
      canonicalizeRegionPaths(code, PKG_DIR, PARENT_DIR),
    );
  });

  it("非绝对包根或基准 ⇒ 无从解析，整串原样交回", () => {
    const code = artifactOf([FOO_LIB]);
    assert.equal(canonicalizeRegionPaths(code, "foo", "."), code);
  });

  it("横幅后必须是路径形状：带空白/引号/反引号的内容不改", () => {
    const code = [
      "// lib/a b.ts",
      '// "lib/a.ts"',
      "// `lib/a.ts`",
      "//#region see the docs",
      "//TODO lib/a.ts",
    ].join("\n");
    assert.equal(canonicalizeRegionPaths(code, PKG_DIR, WORKSPACE), code);
  });

  it("crlf 行尾不丢", () => {
    const code = ["// plugins/foo/lib/a.ts", CODE_LINE].join("\r\n");
    const expected = [LIB_A_MARK, CODE_LINE].join("\r\n");
    assert.equal(canonicalizeRegionPaths(code, PKG_DIR, WORKSPACE), expected);
  });

  it("空文本与无横幅文本都是自身不动点", () => {
    assert.equal(canonicalizeRegionPaths("", PKG_DIR), "");
    const plain = `${CODE_LINE}\n`;
    assert.equal(canonicalizeRegionPaths(plain, PKG_DIR), plain);
  });

  it("残余边界：字符串内容里的同形行仍会被改写", () => {
    // 内部构建不调用本函数，因此产物不承担这条风险；公开子路径只应按“生成代码”使用。
    const code = ["const s = `", "// ../shared/lib/x.ts", "`;"].join("\n");
    assert.equal(
      canonicalizeRegionPaths(code, PKG_DIR, PKG_DIR),
      ["const s = `", SHARED_X_MARK, "`;"].join("\n"),
    );
  });
});

describe("windows 与 unc 的根", () => {
  it("盘符路径按路径段解析；盘符与段大小写不敏感", () => {
    assert.deepEqual(folded([FOO_LIB], String.raw`C:\repo\foo`, String.raw`C:\repo`), [LIB_A_MARK]);
    assert.deepEqual(folded(["FOO/lib/a.ts"], String.raw`C:\repo\foo`, String.raw`c:\REPO`), [
      LIB_A_MARK,
    ]);
  });

  it("POSIX 包根 + 盘符绝对标记 ⇒ 跨平台根，原样保留", () => {
    const raw = String.raw`C:\repo\foo\lib\a.ts`;
    assert.deepEqual(folded([raw], PKG_DIR, PKG_DIR), [`// ${raw}`]);
  });

  it("盘符不同 ⇒ 目标在包外，原样保留", () => {
    const raw = FOO_LIB;
    assert.deepEqual(folded([raw], String.raw`D:\repo\foo`, String.raw`C:\repo`), [`// ${raw}`]);
  });

  it("unc 的 server/share 是根：同 share 内可解析，跨 share 原样保留", () => {
    const pkg = String.raw`\\srv\shareA\foo`;
    assert.deepEqual(folded([FOO_LIB], pkg, String.raw`\\srv\shareA`), [LIB_A_MARK]);
    const cross = "../shareA/foo/lib/a.ts";
    assert.deepEqual(folded([cross], pkg, String.raw`\\srv\shareB`), [`// ${cross}`]);
  });

  it("根目录没有父目录：只按包根判，跨目录路径原样", () => {
    assert.deepEqual(folded(["foo/a.ts"], "/foo", "/"), ["// a.ts"]);
    assert.deepEqual(folded(["bar/a.ts"], "/foo", "/"), ["// bar/a.ts"]);
    assert.deepEqual(folded(["foo/a.ts"], "/", "/"), ["// foo/a.ts"]);
  });

  it("盘符根没有父目录：跨盘路径原样", () => {
    const raw = "D:/repo/a.ts";
    assert.deepEqual(folded([raw], "C:\\", "C:\\"), [`// ${raw}`]);
  });
});

describe("无法解析的路径：整串原样交回", () => {
  it("无效 UNC 包根或基准 ⇒ 不做任何改写", () => {
    const code = artifactOf([FOO_LIB]);
    assert.equal(canonicalizeRegionPaths(code, String.raw`\\srv`, WORKSPACE), code);
    assert.equal(canonicalizeRegionPaths(code, PKG_DIR, String.raw`\\srv`), code);
  });

  it("无效 UNC 横幅（缺 share）⇒ 该行原样", () => {
    assert.deepEqual(folded(["//srv"], PKG_DIR, WORKSPACE), ["// //srv"]);
  });

  it("基准是相对路径 ⇒ 不做任何改写", () => {
    const code = artifactOf([FOO_LIB]);
    assert.equal(canonicalizeRegionPaths(code, PKG_DIR, "plugins"), code);
  });
});
