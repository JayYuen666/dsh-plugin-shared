// lib/canonicalize-region-paths 单元测试：产物里的 `//#region` 行必须与 process.cwd() 无关。
//
// 为什么单独测（而不是只靠各包的 freshness 检查）：那两道检查比的是「同一进程内两侧同形」，
// 换 cwd 时两侧一起漂移，检查照样通过。真正的标准是「两种 cwd 下的字节相等」，只有把两种
// 实测形态当测试数据固定在这里才约束得住。
//
// 测试数据取的是实测到的真实形态（session-rescue 的 host/client 与 shared 自身），不是编出来的形状。
import { describe, it } from "vitest";
import assert from "node:assert/strict";
import { canonicalizeRegionPaths } from "../lib/canonicalize-region-paths.ts";

/** 包根绝对路径（builder 侧就是 import.meta.dirname）。 */
const PKG_DIR = "/repo/plugins/session-rescue";

/** 产物里的一行真代码：用来证明「非 region 字节一个不动」。 */
const CODE_LINE = "const a = 1;";

/** 产物首行的生成说明（builder 写的，不参与规范化）。 */
const GENERATED_BANNER = "// GENERATED by build-host.mjs";

/**
 * 拼一段产物文本（说明行 + 逐行 region 标记 + 一行真代码）。
 * @param marks - 各模块路径，按 rolldown 的写法逐条成行
 * @returns 可直接喂给被测函数的多行文本
 */
function artifactOf(marks: string[]): string {
  const rows = marks.map((mark) => `//#region ${mark}`);
  return [GENERATED_BANNER, ...rows, CODE_LINE].join("\n");
}

/**
 * 抽出产物文本里的全部 `//#region` 行。
 * @param code - 产物文本
 * @returns 命中的行
 */
function regionLines(code: string): string[] {
  return code.split("\n").filter((line) => line.startsWith("//#region"));
}

/** 期望侧的 region 行构造器；传给迭代器时用内联箭头（lint 规则要求），直调时用它。 */
const foldedMark = (mark: string): string => `//#region ${mark}`;

/**
 * 造一段产物、改写成 canonical、只回 region 行（各用例的主要判断形态）。
 * @param marks - 某个 cwd 下 rolldown 实际写出的模块路径
 * @param pkgDir - 交给被测函数的包根（默认本文件顶上的那枚）
 * @returns 折完之后的 region 行
 */
function foldedRegionLines(marks: string[], pkgDir: string = PKG_DIR): string[] {
  const folded = canonicalizeRegionPaths(artifactOf(marks), pkgDir);
  return regionLines(folded);
}

describe("带包名前缀的行 ⇒ 折回相对包根", () => {
  it("cwd = plugins/ 的形态 ⇒ 前缀消失", () => {
    const folded = foldedRegionLines(["session-rescue/lib/failure-classify.ts"]);
    assert.deepEqual(folded, ["//#region lib/failure-classify.ts"]);
  });

  it("cwd = 包根的形态 ⇒ 逐字节不变", () => {
    const current = artifactOf(["lib/turn-facts.ts"]);
    assert.equal(canonicalizeRegionPaths(current, PKG_DIR), current);
  });

  it("两处 cwd 的实测形态折完 ⇒ 两串相等（可复现性的正面判据）", () => {
    const fromPkgCwd = artifactOf(["host.ts", "lib/resume-scheduler.ts"]);
    const fromPluginsCwd = artifactOf([
      "session-rescue/host.ts",
      "session-rescue/lib/resume-scheduler.ts",
    ]);
    const pkgFolded = canonicalizeRegionPaths(fromPkgCwd, PKG_DIR);
    const pluginsFolded = canonicalizeRegionPaths(fromPluginsCwd, PKG_DIR);
    assert.equal(pkgFolded, pluginsFolded);
  });

  it("工作区根当 cwd 时是两段前缀 ⇒ 一并折回", () => {
    const folded = foldedRegionLines(["plugins/session-rescue/turn-review.ts"]);
    assert.deepEqual(folded, ["//#region turn-review.ts"]);
  });

  it("cwd = DSH_HOME 时的跨包依赖多一段父目录 ⇒ 只收父目录段", () => {
    const folded = foldedRegionLines(["plugins/shared/lib/errors.ts"]);
    assert.deepEqual(folded, ["//#region shared/lib/errors.ts"]);
  });

  it("锚点只认行首：路径中段的 plugins 不参与收折", () => {
    const current = artifactOf(["node_modules/webpack/plugins/index.js"]);
    assert.equal(canonicalizeRegionPaths(current, PKG_DIR), current);
  });

  it("包名只按整段匹配：文件名恰为包名时不是前缀命中", () => {
    const current = artifactOf(["lib/session-rescue.ts"]);
    assert.equal(canonicalizeRegionPaths(current, PKG_DIR), current);
  });
});

describe("行首相对段折叠：跨包依赖在两种 cwd 下同形", () => {
  it("../shared 与同级的 shared ⇒ 折完相等", () => {
    const fromPkgCwd = foldedRegionLines(["../shared/lib/record.ts"]);
    const fromPluginsCwd = foldedRegionLines(["shared/lib/record.ts"]);
    assert.deepEqual(fromPkgCwd, fromPluginsCwd);
    assert.deepEqual(fromPkgCwd, ["//#region shared/lib/record.ts"]);
  });

  it("../node_modules 与 ./node_modules ⇒ 都收成裸 node_modules", () => {
    const fromParent = foldedRegionLines(["../node_modules/x/index.js"]);
    const fromSelf = foldedRegionLines(["./node_modules/y/index.cjs"]);
    assert.deepEqual(fromParent, ["//#region node_modules/x/index.js"]);
    assert.deepEqual(fromSelf, ["//#region node_modules/y/index.cjs"]);
  });

  it("连续多枚行首相对段也一次收尽", () => {
    const folded = foldedRegionLines(["../../shared/lib/locale.ts"]);
    assert.deepEqual(folded, ["//#region shared/lib/locale.ts"]);
  });

  it("包名前缀与行首相对段同时出现（sibling cwd）⇒ 先折叠再折前缀", () => {
    const folded = foldedRegionLines(["../session-rescue/src/ui-messages.ts"]);
    assert.deepEqual(folded, ["//#region src/ui-messages.ts"]);
  });
});

describe("射程只有 //#region 那一行的路径文本", () => {
  it("//#endregion 与非 region 行原样保留", () => {
    const code = ["//#endregion", "  const b = 2;", "//#regionless host.ts"].join("\n");
    assert.equal(canonicalizeRegionPaths(code, PKG_DIR), code);
  });

  it("代码中间的同形字符串不被改写（判据是整行行首）", () => {
    const line = String.raw`  const note = "//#region session-rescue/lib/messages.ts";`;
    assert.equal(canonicalizeRegionPaths(line, PKG_DIR), line);
  });

  it("跨行模板字面量里以标记起行、但不像路径（含空白）的内容原样保留", () => {
    // 行首锚点挡不住跨行字面量：这一层由「标记后必须像模块路径」的形态检查拦下，
    // 运行时字符串值不得被改写。
    const code = "const s = `\n//#region see the docs for the full list\n`;";
    assert.equal(canonicalizeRegionPaths(code, PKG_DIR), code);
  });

  it("残余局限：跨行字面量里与真标记逐字符同形的内容仍会被改写（纯字符串分析无从区分）", () => {
    // 刻意固定这一条而不是假装它不存在：什么时候有人给出可区分的判断方法，改的也是这里。
    const code = "const s = `\n//#region session-rescue/lib/messages.ts\n`;";
    assert.equal(
      canonicalizeRegionPaths(code, PKG_DIR),
      "const s = `\n//#region lib/messages.ts\n`;",
    );
  });

  it("生成说明行与真代码行不参与改写", () => {
    const folded = canonicalizeRegionPaths(artifactOf(["session-rescue/lib/messages.ts"]), PKG_DIR);
    const rows = folded.split("\n");
    assert.equal(rows[0], GENERATED_BANNER, "GENERATED 说明行被改写了");
    assert.equal(rows.at(-1), CODE_LINE, "真代码行被改写了");
  });

  it("换行为 CRLF 时行尾不丢", () => {
    const code = ["//#region session-rescue/lib/jsonl.ts", CODE_LINE].join("\r\n");
    const expected = ["//#region lib/jsonl.ts", CODE_LINE].join("\r\n");
    assert.equal(canonicalizeRegionPaths(code, PKG_DIR), expected);
  });
});

describe("包根字符串的边界形状", () => {
  it("pkgDir 末段带分隔符 ⇒ 与不带时同一结果", () => {
    const code = artifactOf(["session-rescue/lib/errors.ts"]);
    const withSeparator = canonicalizeRegionPaths(code, `${PKG_DIR}/`);
    const withoutSeparator = canonicalizeRegionPaths(code, PKG_DIR);
    assert.equal(withSeparator, withoutSeparator);
  });

  it("pkgDir 没有分隔符 ⇒ 整串当包名", () => {
    const folded = foldedRegionLines(["lesson-loop/host.ts"], "lesson-loop");
    assert.deepEqual(folded, ["//#region host.ts"]);
  });

  it("pkgDir 只剩分隔符 ⇒ 无从取名，整串原样交回", () => {
    const code = artifactOf(["some-consumer/lib/card-store.ts"]);
    assert.equal(canonicalizeRegionPaths(code, "/"), code);
    assert.equal(canonicalizeRegionPaths(code, "\\"), code);
  });

  it("shared 自己的产物：段名里的 shared 不是段边界 ⇒ 不误折", () => {
    // `@jayyuen66/dsh-plugin-shared` 与 `dsh-brand` 都只以**子串**含包名，整段匹配不命中，
    // 于是本用例只有行首的 `../` 被收掉，路径的其余部分一字不动。
    const expected = artifactOf([
      "node_modules/@jayyuen66/dsh-plugin-shared/lib/index.js",
      "node_modules/.pnpm/@deepseek-ai+dsh-brand@0.2.0/node_modules/@deepseek-ai/dsh-brand/lib/index.js",
    ]);
    const folded = canonicalizeRegionPaths(
      artifactOf([
        "../node_modules/@jayyuen66/dsh-plugin-shared/lib/index.js",
        "../node_modules/.pnpm/@deepseek-ai+dsh-brand@0.2.0/node_modules/@deepseek-ai/dsh-brand/lib/index.js",
      ]),
      "/repo/plugins/shared",
    );
    assert.equal(folded, expected);
  });
});

describe("幂等", () => {
  it("对 canonical 文本二次调用逐字符不变", () => {
    const marks = [
      "session-rescue/lib/dock-state.ts",
      "../shared/lib/card-apply.ts",
      "node_modules/.pnpm/@deepseek-ai+dsh-jobs@0.2.0/index.js",
    ];
    const once = canonicalizeRegionPaths(artifactOf(marks), PKG_DIR);
    const twice = canonicalizeRegionPaths(once, PKG_DIR);
    assert.equal(twice, once);
    assert.equal(canonicalizeRegionPaths(twice, PKG_DIR), once);
  });

  it("空文本与无 region 行的文本都是自身不动点", () => {
    assert.equal(canonicalizeRegionPaths("", PKG_DIR), "");
    const plain = `${CODE_LINE}\n`;
    assert.equal(canonicalizeRegionPaths(plain, PKG_DIR), plain);
  });
});

// cwd 精确档：前缀按 rel(cwd, …) 计算，不再按段名猜。用例形态取自「包内目录与父目录同名」
// 这一反例——按名猜测的两档的失败方式（误改、跨 cwd 不同形、不幂等）在这里都必须表现为不失败。
describe("cwd 精确档：包内目录与父目录同名不被误折", () => {
  /** 包根 /repo/plugins/foo，包内存在真实目录 plugins/（与父目录段同名）。 */
  const COLLIDING_PKG = "/repo/plugins/foo";
  const WORKSPACE = "/repo";
  const COLLIDING_MARK_PKG_CWD = "plugins/x.ts";
  const COLLIDING_MARK_ANCESTOR_CWD = "plugins/foo/plugins/x.ts";
  const BARE_PKG_MARK = "pkg/lib/a.ts";
  const DEP_HELPER = "deps/lib/helper.ts";

  it("cwd = 包根：包内真实目录原样保留", () => {
    const folded = canonicalizeRegionPaths(
      artifactOf([COLLIDING_MARK_PKG_CWD]),
      COLLIDING_PKG,
      COLLIDING_PKG,
    );
    assert.deepEqual(regionLines(folded), [foldedMark(COLLIDING_MARK_PKG_CWD)]);
  });

  it("cwd = 工作区根：只收 rel(cwd, 包根)，包内目录仍在", () => {
    const folded = canonicalizeRegionPaths(
      artifactOf([COLLIDING_MARK_ANCESTOR_CWD]),
      COLLIDING_PKG,
      WORKSPACE,
    );
    assert.deepEqual(regionLines(folded), [foldedMark(COLLIDING_MARK_PKG_CWD)]);
  });

  it("两种 cwd 折完同形，且对 canonical 文本幂等", () => {
    const fromPkg = canonicalizeRegionPaths(
      artifactOf([COLLIDING_MARK_PKG_CWD]),
      COLLIDING_PKG,
      COLLIDING_PKG,
    );
    const fromAncestor = canonicalizeRegionPaths(
      artifactOf([COLLIDING_MARK_ANCESTOR_CWD]),
      COLLIDING_PKG,
      WORKSPACE,
    );
    assert.equal(fromPkg, fromAncestor);
    assert.equal(canonicalizeRegionPaths(fromPkg, COLLIDING_PKG, COLLIDING_PKG), fromPkg);
  });

  it("自有模块跨 cwd 同形；pkgDir 尾随分隔符不影响前缀", () => {
    const fromPkg = canonicalizeRegionPaths(artifactOf(["lib/a.ts"]), COLLIDING_PKG, COLLIDING_PKG);
    const fromAncestor = canonicalizeRegionPaths(
      artifactOf(["plugins/foo/lib/a.ts"]),
      COLLIDING_PKG,
      WORKSPACE,
    );
    const fromAncestorTrailingSep = canonicalizeRegionPaths(
      artifactOf(["plugins/foo/lib/a.ts"]),
      `${COLLIDING_PKG}/`,
      WORKSPACE,
    );
    assert.equal(fromAncestor, fromPkg);
    assert.equal(fromAncestorTrailingSep, fromPkg);
  });

  it("同级依赖只收父目录前缀，依赖包名保留", () => {
    const fromAncestor = canonicalizeRegionPaths(
      artifactOf([`plugins/${DEP_HELPER}`]),
      COLLIDING_PKG,
      WORKSPACE,
    );
    const fromPkg = canonicalizeRegionPaths(
      artifactOf([`../${DEP_HELPER}`]),
      COLLIDING_PKG,
      COLLIDING_PKG,
    );
    assert.deepEqual(regionLines(fromAncestor), [foldedMark(DEP_HELPER)]);
    assert.equal(fromPkg, fromAncestor);
  });

  it("cwd = 包根父目录：自有模块收包名段，依赖与 node_modules 原样", () => {
    const marks = ["lib/a.ts", DEP_HELPER, "node_modules/x/index.js"];
    const folded = canonicalizeRegionPaths(artifactOf(marks), COLLIDING_PKG, "/repo/plugins");
    assert.deepEqual(
      regionLines(folded),
      marks.map((mark) => `//#region ${mark}`),
    );
  });

  it("cwd 在包根之下：行首相对段收掉后即 canonical", () => {
    const marks = ["lib/a.ts", DEP_HELPER];
    const folded = canonicalizeRegionPaths(
      artifactOf(["../lib/a.ts", `../../${DEP_HELPER}`]),
      COLLIDING_PKG,
      `${COLLIDING_PKG}/sub`,
    );
    assert.deepEqual(
      regionLines(folded),
      marks.map((mark) => `//#region ${mark}`),
    );
  });

  it("cwd = 包根的兄弟目录：行首相对段收掉后按剩余前缀收", () => {
    const marks = ["lib/a.ts", DEP_HELPER];
    const folded = canonicalizeRegionPaths(
      artifactOf(["../plugins/foo/lib/a.ts", `../plugins/${DEP_HELPER}`]),
      COLLIDING_PKG,
      "/repo/other",
    );
    assert.deepEqual(
      regionLines(folded),
      marks.map((mark) => `//#region ${mark}`),
    );
  });

  it("无关绝对路径（node_modules）与中段同名都不收", () => {
    const marks = ["node_modules/webpack/plugins/index.js", "lib/plugins-helper.ts"];
    const folded = canonicalizeRegionPaths(artifactOf(marks), COLLIDING_PKG, WORKSPACE);
    assert.deepEqual(
      regionLines(folded),
      marks.map((mark) => `//#region ${mark}`),
    );
  });

  it("盘符不同 ⇒ rel 无从算起，只收行首相对段", () => {
    const marks = ["pkg/lib/a.ts", "pkg/lib/b.ts"];
    const folded = canonicalizeRegionPaths(
      artifactOf([BARE_PKG_MARK, `../${BARE_PKG_MARK.replace("a", "b")}`]),
      String.raw`D:\repo\pkg`,
      String.raw`C:\repo`,
    );
    assert.deepEqual(
      regionLines(folded),
      marks.map((mark) => `//#region ${mark}`),
    );
  });

  it("一侧绝对一侧相对 ⇒ 同上，不收前缀", () => {
    const folded = canonicalizeRegionPaths(artifactOf([BARE_PKG_MARK]), "/repo/pkg", "repo");
    assert.deepEqual(regionLines(folded), [foldedMark(BARE_PKG_MARK)]);
  });

  it("裸名包根（无分隔符）也走精确档", () => {
    const folded = canonicalizeRegionPaths(
      artifactOf([BARE_PKG_MARK, `../${DEP_HELPER}`]),
      "pkg",
      ".",
    );
    assert.deepEqual(regionLines(folded), [foldedMark("lib/a.ts"), foldedMark(DEP_HELPER)]);
  });
});

describe("旧签名档的父锚点边界", () => {
  it("pkgDir 末段带分隔符 ⇒ 父锚点仍取整段而非被截断的残段", () => {
    // 短包根加尾随分隔符是父锚点被截成残段的形状：残段匹配不到任何行首，父目录前缀会漏收。
    const folded = canonicalizeRegionPaths(
      artifactOf(["plugins/shared/lib/x.ts"]),
      "/repo/plugins/foo/",
    );
    assert.deepEqual(regionLines(folded), ["//#region shared/lib/x.ts"]);
  });
});
