// 集成测试：**真 rolldown** 在一个临时 fixture 包上跑完整构建链——所有真构建检查此前
// 只验证过 shared 自己的布局（build-host.test.ts），stub 编排测试的输出形状是手写假设；
// 「stub 假设 == rolldown 现实」只有真工具链能证。断言落在结构特征（自包含单文件、
// 依赖外部化、生成头、json 数据内联）而不是字节，避免对 rolldown 产物的字节级脆弱断言。
import { describe, it } from "vitest";
import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile, mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { rolldown } from "rolldown";

import { buildHostEntries } from "../../lib/build-host.ts";
import { buildClientBundle } from "../../lib/build-client.ts";

const HEADER = "// GENERATED by integration fixture\n";

interface Fixture {
  root: string;
}

async function makeFixture(): Promise<Fixture> {
  const root = await mkdtemp(path.join(tmpdir(), "shared-fixture-"));
  await mkdir(path.join(root, "src"), { recursive: true });
  await writeFile(
    path.join(root, "package.json"),
    JSON.stringify({
      name: "fixture-pkg",
      dependencies: { "some-external-dep": "1.0.0" },
      optionalDependencies: { "some-optional-dep": "1.0.0" },
    }),
    "utf8",
  );
  // 宿主入口：本地 helper + json 数据 + 一条外部化依赖，三种来源各占一席。
  await writeFile(
    path.join(root, "host.ts"),
    [
      `import { helper } from "./src/helper.ts";`,
      `import data from "./src/data.json" with { type: "json" };`,
      `import { externalApi } from "some-external-dep";`,
      `import { optionalApi } from "some-optional-dep";`,
      `export const name = "fixture-pkg";`,
      `export function render(): string {`,
      `  return \`\${helper()}-\${data.count}-\${externalApi()}-\${optionalApi()}\`;`,
      `}`,
      "",
    ].join("\n"),
    "utf8",
  );
  await writeFile(
    path.join(root, "src", "helper.ts"),
    'export function helper(): string {\n  return "helper-value";\n}\n',
    "utf8",
  );
  await writeFile(path.join(root, "src", "data.json"), JSON.stringify({ count: 7 }), "utf8");
  // 客户端入口：React 运行时是缺省外置面（REACT_RUNTIME_MODULES）。
  await writeFile(
    path.join(root, "client-entry.ts"),
    `import { createElement } from "react";\nexport const el = createElement("div");\n`,
    "utf8",
  );
  return { root };
}

describe("真 rolldown 的 fixture 构建链", () => {
  it("宿主入口打成自包含单文件：本地代码与 json 内联、外部依赖保持裸说明符", async () => {
    const { root } = await makeFixture();
    try {
      const artifacts = await buildHostEntries({
        root,
        rolldown,
        resolveExtensions: [".ts", ".mjs", ".js", ".json"],
        entries: [{ source: "host.ts", output: "host.js", header: HEADER }],
      });
      assert.equal(artifacts.length, 1);
      const [artifact] = artifacts;
      assert.ok(artifact !== undefined);
      assert.ok(artifact.code.startsWith(HEADER), "生成头是产物字节的一部分");
      // 本地 helper 与 json 数据被内联（自包含）：函数体与数据值都在产物里。
      assert.ok(artifact.code.includes("helper-value"), "本地 helper 未内联");
      assert.ok(
        artifact.code.includes('"count"') || artifact.code.includes("count"),
        "json 数据未内联",
      );
      // 外部化：裸说明符原样保留（外部名单内的包名一旦内联即缺陷）。
      assert.ok(artifact.code.includes("some-external-dep"), "依赖未外部化");
      assert.ok(artifact.code.includes("some-optional-dep"), "可选依赖未外部化");
      // 无残缺的相对 TS 说明符（./x.ts 残留是构建回归的典型形状）。
      assert.equal(
        /from\s+["']\.\.?\/[^"']*\.ts["']/u.test(artifact.code),
        false,
        "产物残留 .ts 说明符",
      );
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  }, 60_000);

  it("客户端入口打成 require 门面：react 家族外置、无本地实现内联", async () => {
    const { root } = await makeFixture();
    try {
      const client = await buildClientBundle({
        root,
        rolldown,
        entry: "client-entry.ts",
        header: HEADER,
      });
      assert.ok(client.startsWith(HEADER));
      assert.ok(client.includes("react"), "react 未外置");
      // client.js 只留 require 门面：local 入口的实现不该被复制进来。
      assert.equal(client.includes('createElement("div")'), false, "入口实现被内联进 client.js");
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  }, 60_000);
});
