#!/usr/bin/env node
/// <reference types="node" />
// 构建 dist/client.js：共享客户端行的 UMD bundle。消费者只 require
// `@jayyuen66/dsh-plugin-shared/client`，宿主模块图层按包名提供这一份。
// 入口与产物路径是手写约定；共用编排仍定义在 lib/build-client.ts（本包不能引用自己
// 尚未发布的 dist/build 面，故直接取源码）。
import path from "node:path";
import { mkdir, writeFile } from "node:fs/promises";
import { buildClientBundle, REACT_RUNTIME_MODULES } from "./lib/build-client.ts";
import { isMainModule } from "./build-shared.mjs";

const root = import.meta.dirname;
const entry = "lib/client-entry.ts";

/** 生成客户端行的 UMD 文本。 */
export async function buildClient() {
  const { rolldown } = await import("rolldown");
  return buildClientBundle({
    root,
    rolldown,
    entry,
    externals: REACT_RUNTIME_MODULES,
    header: `// GENERATED by build-client.mjs — edit ${entry}, then run \`node build-client.mjs\`.`,
  });
}

async function main() {
  const out = await buildClient();
  const outDir = path.join(root, "dist");
  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, "client.js"), out, "utf8");
  console.info("client built:", Buffer.byteLength(out, "utf8"), "bytes -> dist/client.js");
}

if (isMainModule(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
